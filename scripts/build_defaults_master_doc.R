# --- the table that did not exist before -----------------------------------
out <- c(out, "## Effective value of every parameter, per sub-category", "",
  "What the app actually fills in, from `resolve_subcat_default()`: the generic default, then any per-sub-category override, then the biological zeros (no milk, fat or milk protein for males; no pregnancy for males or calves; no work hours except oxen). `source` distinguishes them.", "",
  "| sub_category | parameter | value | distribution | source |",
  "|---|---|---|---|---|")
for (sc in ANIMAL_SUBCATEGORIES) for (prm in PARAM_CATALOGUE$parameter) {
  r <- tryCatch(resolve_subcat_default(sc, prm), error = function(e) NULL)
  if (is.null(r)) next
  gen <- PARAM_CATALOGUE$ipcc_default[PARAM_CATALOGUE$parameter == prm]
  src <- if (identical(r$data_source, "biological_zero")) "biological zero"
         else if (!is.na(r$value) && !is.na(gen) && !isTRUE(all.equal(r$value, gen)))
           "sub-category override"
         else "catalogue default"
  out <- c(out, sprintf("| %s | %s | %s | %s | %s |", sc, prm,
                        fmt(r$value), r$distribution, src))
}

