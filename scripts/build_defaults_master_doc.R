fmt <- function(x) {
  if (is.null(x) || length(x) == 0) return("")
  if (is.na(x)) return("")
  if (is.logical(x)) return(if (x) "yes" else "no")
  n <- suppressWarnings(as.numeric(x))
  if (!is.na(n)) format(n, scientific = FALSE, trim = TRUE, drop0trailing = TRUE)
  else gsub("\\|", "\\\\|", as.character(x))
}
tbl <- function(d, cols = names(d)) {
  c(paste0("| ", paste(cols, collapse = " | "), " |"),
    paste0("|", paste(rep("---", length(cols)), collapse = "|"), "|"),
    vapply(seq_len(nrow(d)), function(i)
      paste0("| ", paste(vapply(cols, function(k) fmt(d[[k]][i]),
                                character(1)), collapse = " | "), " |"),
      character(1)))
}

