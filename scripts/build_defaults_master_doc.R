# =============================================================================
# build_defaults_master_doc.R -- render the master CSV as a readable document
# =============================================================================
#
# reference/defaults_master.csv is the authority but is long-format and awkward
# to read. This renders it as reference/DEFAULTS_MASTER.md: wide tables per
# object, plus the table that did not exist anywhere before -- the EFFECTIVE
# value of every parameter for every sub-category, including the overrides and
# biological zeros that resolve_subcat_default() applies at run time.
#
# Generated, never hand-edited. Edit the CSV and re-run.
#
# Usage (from project root):
#   Rscript scripts/build_defaults_master_doc.R
# =============================================================================

